type Pixel = { x: number; y: number; width: number; tone: string };
function pixels(sprite: string): Pixel[] {
    const rows = sprite.trim().split('\n');
    const top = Math.floor((16 - rows.length) / 2);
    return rows.flatMap((row, y) => {
        const runs: Pixel[] = [];
        for (let x = 0; x < row.length;) {
            const tone = row[x]!; let end = x + 1;
            while (row[end] === tone) end++;
            if (tone !== '.') runs.push({ x, y: top + y, width: end - x, tone });
            x = end;
        }
        return runs;
    });
}
const artwork = Object.fromEntries(Object.entries(sprites).map(([name, sprite]) => [name, pixels(sprite)])) as Record<IconName, Pixel[]>;
export default function GameIcon({ name, className = '' }: { name: IconName; className?: string }) {
    return <svg className={`game-icon ${className}`} data-icon={name} viewBox="-1 -1 18 18" shapeRendering="crispEdges" aria-hidden="true" focusable="false">{artwork[name].map((pixel, i) => <rect key={i} x={pixel.x} y={pixel.y} width={pixel.width} height="1" className={`pixel-${pixel.tone === '#' ? 'edge' : pixel.tone === 'h' ? 'shine' : pixel.tone === '-' ? 'shade' : 'material'}`} />)}</svg>;
}
export function RankBadge({ rank, decorative = false }: { rank: string; decorative?: boolean }) {
    const tier = Math.max(0, ['E', 'D', 'C', 'B', 'A', 'S'].indexOf(rank));
    return <svg className="rank-badge" data-rank={rank} viewBox="0 0 64 72" shapeRendering="crispEdges" role={decorative ? undefined : 'img'} aria-label={decorative ? undefined : `Rank ${rank}`} aria-hidden={decorative || undefined}>
        {Array.from({ length: Math.min(3, tier) }, (_, i) => <g key={i} className="rank-wings"><path d={`M${12-i*3} ${24+i*8}H${6-i*2}v8h4v8h6v-8h-4Z M${52+i*3} ${24+i*8}h${6-i}v8h-4v8h-6v-8h4Z`} /></g>)}
        <path className="rank-shell" d="M16 4h32v4h8v40h-4v8h-8v4h-8v8h-8v-8h-8v-4h-8v-8H8V8h8Z" />
        <path className="rank-inner" d="M18 10h28v4h4v32h-4v6h-8v4H26v-4h-8v-6h-4V14h4Z" />
        <path className="rank-facet" d="M18 10h28v4H20v32h-6V14h4Z" />
        {Array.from({ length: tier + 1 }, (_, i) => <rect className="rank-star" key={i} x={32 + (i - tier / 2) * 5 - 1} y="18" width="3" height="3" />)}
        <text x="32" y="43" textAnchor="middle">{rank}</text><path className="rank-facet" d="M28 52h8v4h-8Z" />
    </svg>;
}
